package dataloggers;

import java.io.IOException;

import javax.swing.SwingWorker;

import com.nomagic.magicdraw.ui.notification.Notification;
import com.nomagic.magicdraw.ui.notification.NotificationManager;

/**
 * @author kata_du
 * @version 1.0.0
 * @date 2025-12-18
 * @summary The `BackgroundRunner` class is responsible for executing tasks in the background and providing notifications for these tasks.
 */
public class BackgroundRunner {

	// Initialize the logger, passing *this* runner to its constructor.
    // NOTE: This assumes ModelCallLogger is modified to accept a BackgroundRunner.
	ModelCallLogger logger = new ModelCallLogger(this); 

/**
 * @param ID The `ID` parameter in the `Notifyinbackground` method is a unique identifier for the notification being displayed.
 * @param Prompt The `Prompt` parameter is a `String` that specifies the message to be displayed in the notification.
 * @summary The method `Notifyinbackground` initiates a background task to display a notification with the given ID and prompt.
 */
	public void Notifyinbackground(String ID, String Prompt) {
        SwingWorker<Void, Void> worker = new SwingWorker<Void, Void>() {
/**
 * @return The return value of the `doInBackground` method indicates that it does not produce any meaningful output. Its primary purpose is to execute background tasks such as displaying a notification using the `NotificationManager`.
 * @summary The primary responsibility of the `doInBackground` method is to display a notification with specific parameters using the `NotificationManager`.
 */
            @Override
            protected Void doInBackground() throws Exception {
            	NotificationManager.getInstance().showNotification(new Notification(ID,Prompt,null));
                return null;
            }
        };
        worker.execute();
	}
	
/**
 * @param task The `task` parameter is a `Runnable` object that encapsulates the code to be executed asynchronously in the background.
 * @summary The `DoInBackground` method executes a given runnable task asynchronously using a `SwingWorker`.
 */
	public void DoInbackground(Runnable task)throws IOException {
        SwingWorker<Void, Void> worker = new SwingWorker<Void, Void>() {
/**
 * @return The `doInBackground` method executes a specified task in the background and returns nothing, indicated by the `Void` type. This is consistent with its purpose of performing a lengthy operation asynchronously without returning any result to the calling thread.
 * @summary The `doInBackground` method executes the given `task` in a background thread and returns no result, primarily used for asynchronous processing within the OSIRIS plugin framework.
 */
            @Override
            protected Void doInBackground() throws Exception {
                task.run();
                return null;
            }
        };
        worker.execute();
	}
	

/**
 * @param currentTry The `currentTry` parameter represents the attempt count for logging the model information in the background.
 * @param modelName2 The `modelName2` parameter represents the name of the SysML model being logged.
 * @param sys_Msg The `sys_Msg` parameter is a descriptive message related to the system's current state or context that will be logged along with other relevant information.
 * @param prompt The `prompt` parameter is a String that represents the input or query provided to the language model for generating relevant responses.
 * @param string The `string` parameter in the `logModelInbackground` method represents an additional context-specific message or identifier used for logging purposes.
 * @param response The `response` parameter is the String output generated by a process or system that needs to be logged for tracking and analysis.
 * @summary The `logModelInbackground` method asynchronously logs model-related information using SwingWorker to handle background processing.
 */
	public void logModelInbackground(int currentTry, String modelName2, String sys_Msg, String prompt, String string, String response) {
        SwingWorker<Void, Void> worker = new SwingWorker<Void, Void>() {
/**
 * @return The `doInBackground` method does not return any meaningful data; its primary purpose is to execute background tasks and log relevant information.
 * @summary The method `doInBackground` logs the current attempt details along with various parameters to a logger.
 */
            @Override
            protected Void doInBackground() throws Exception {
            	logger.log(currentTry, modelName2, sys_Msg, prompt, string,response);
                return null;
            }
        };
        worker.execute();
		
	}
}
