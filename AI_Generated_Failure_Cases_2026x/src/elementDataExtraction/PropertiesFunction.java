/**
 * @param selectedNode The `selectedNode` parameter represents the SysML model element currently selected for updating its associated system elements.
 * @return The `UpdateSystemListForFunctionElement` method returns a `List<Element>` containing the system elements related to the input function or activity node. This list is generated by querying the relevant systems associated with the selected node, which can be either an action (such as a CallBehaviorAction) or an activity element within the SysML model. The returned list represents the context of systems pertinent to the given function or activity element and is used for further processing in Functional Hazard Assessment (FHA).
 * @summary This method retrieves a list of system elements associated with a given function element within a SysML model.
 */
	public  List<Element> UpdateSystemListForFunctionElement(Element selectedNode) {
		// Check if the key "System" exists in the map
		List<Element> SystemInContext = new ArrayList<>();
		if(selectedNode instanceof Action) {
			// Retrieve the list of systems related to the selected element
			SystemInContext = ActionDC.GetRelatedSystemElement(selectedNode);

			if(SystemInContext.isEmpty() ||SystemInContext==null) {
				if (selectedNode instanceof CallBehaviorAction) {		
					// Get the behavior of the CallBehaviorAction
					var function = ((CallBehaviorAction) selectedNode).getBehavior();

					// Check if the function is not null and cast it to Element
					if (function != null) {
						Element selectedfunction = (Element) function;

						SystemInContext = ActivityDC.GetRelatedSystemElement(selectedfunction);
					}
				}

			}
		}
		if(selectedNode instanceof Activity) {
			// Retrieve the list of systems related to the selected element
			SystemInContext = ActivityDC.GetRelatedSystemElement(selectedNode);
		}
		return SystemInContext;


	}

/**
 * @param propertyMap The `propertyMap` parameter is a mapping of property names to lists of SysML elements used for updating and managing system-related elements in the context of a selected node.
 * @param selectedNode The parameter `selectedNode` of type `Element` in method `UpdateSystemListElement` represents the SysML element that is currently selected for updating its associated system list.
 * @return The return value of the `UpdateSystemListElement` method is a `Map<String, List<Element>>`. This map represents the updated state of system elements associated with a selected node in the SysML model. The key "Systems" in this map holds a list of all unique system elements related to the selected node, ensuring that duplicate entries are avoided and new systems are added as they are discovered through various context checks (e.g., actions or activities). This updated map can be used for further processing or analysis within the OSIRIS plugin.
 * @summary The `UpdateSystemListElement` method updates a map with systems related to a selected element, ensuring no duplicates are added.
 */
	public Map<String, List<Element>> UpdateSystemListElement(Map<String, List<Element>> propertyMap,Element selectedNode) {
		// Check if the key "System" exists in the map
		List<Element> systemList = propertyMap.get("System");
		List<Element> SystemInContext = new ArrayList<>();
		if(selectedNode instanceof Action) {
			// Retrieve the list of systems related to the selected element
			SystemInContext = ActionDC.GetRelatedSystemElement(selectedNode);

			if(SystemInContext.isEmpty() ||SystemInContext==null) {
				if (selectedNode instanceof CallBehaviorAction) {		
					// Get the behavior of the CallBehaviorAction
					var function = ((CallBehaviorAction) selectedNode).getBehavior();

					// Check if the function is not null and cast it to Element
					if (function != null) {
						Element selectedfunction = (Element) function;

						SystemInContext = ActivityDC.GetRelatedSystemElement(selectedfunction);
					}
				}

			}
		}
		if(selectedNode instanceof Activity) {
			// Retrieve the list of systems related to the selected element
			SystemInContext = ActivityDC.GetRelatedSystemElement(selectedNode);
		}

		// If systemList is null, initialize it and add all elements from SystemInContext
		if (systemList == null) {
			systemList = new ArrayList<>(SystemInContext);
			propertyMap.put("Systems", systemList);
		} else {
			// If systemList exists, add elements from SystemInContext that are not already in the systemList
			for (Element system : SystemInContext) {
				if (!systemList.contains(system)) {
					systemList.add(system);
				}
			}
		}
		// Return the updated property map
		return propertyMap;
	}

/**
 * @param functionStereotypeProperties The `functionStereotypeProperties` parameter is a list of elements representing the stereotypes associated with system functions.
 * @param selectedElement The `selectedElement` parameter is the specific SysML element for which the property values are being updated in the map.
 * @param prop The `prop` parameter is the name of the stereotype property to be updated in the function's list.
 * @return The `UpdatePropertyList` method's return value is a map that associates each property name with its corresponding list of associated SysML elements. This map provides an organized collection of the property values retrieved from the selected element, facilitating further processing or analysis within OSIRIS for Functional Hazard Assessment (FHA).
 * @summary The method `UpdatePropertyList` updates a given map with a new list of elements for a specified property from the stereotype of a selected element.
 */
	private Map<String, List<Element>> UpdatePropertyList(Map<String, List<Element>> functionStereotypeProperties,Element selectedElement, String prop) {

		var property = StereotypesHelper.getPropertyByName(functionStereotype, prop);

		List<Element> propertiesValues = new ArrayList<>();

		for (Object value : StereotypesHelper.getStereotypePropertyValue(selectedElement, property))
		{
			if (value instanceof Element) {
				propertiesValues.add((Element) value);
			}
		}

		functionStereotypeProperties.put(prop, propertiesValues);
		return functionStereotypeProperties;
	}

	
	
/**
 * @param propertyMap The `propertyMap` parameter is a mapping of input and output parameters associated with the given action or activity.
 * @param selectedfunctionAction `selectedfunctionAction`: The `Element` representing the currently selected function or action whose input and output parameters are to be updated in the `propertyMap`.
 * @return The `UpdateInputs_Output_List` method returns a `Map<String, List<Element>>` that contains lists of input and output elements associated with the specified function action. The map keys are "InputParameters" for inputs and "OutputParameters" for outputs. If the selected function action is an instance of either `Action` or `Activity`, the corresponding input and output lists are retrieved and updated in the property map before being returned.
 * @summary The `UpdateInputs_Output_List` method updates a given property map with input and output parameters of a selected function or activity.
 */
	private Map<String, List<Element>> UpdateInputs_Output_List(Map<String, List<Element>> propertyMap,Element selectedfunctionAction)
	{

		if(selectedfunctionAction instanceof Action) {

			List<Element> InputList = ActionDC.getInputListElement(selectedfunctionAction);

			List<Element> OutputList = ActionDC.getOutputListElement(selectedfunctionAction);

			propertyMap.put("InputParameters", InputList);

			propertyMap.put("OutputParameters", OutputList);

			// Return the updated property map
			return propertyMap;
		}
		else if (selectedfunctionAction instanceof Activity) {
			List<Element> InputList = ActivityDC.getInputListElement((Activity)selectedfunctionAction);

			List<Element> OutputList = ActivityDC.getOutputListElement((Activity)selectedfunctionAction);

			propertyMap.put("InputParameters", InputList);

			propertyMap.put("OutputParameters", OutputList);
			// Return the updated property map
			return propertyMap;
		}
		return propertyMap;
	}


