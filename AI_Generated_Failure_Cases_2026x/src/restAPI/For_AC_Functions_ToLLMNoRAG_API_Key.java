package restAPI;

import java.io.IOException;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.node.ArrayNode;
import com.fasterxml.jackson.databind.node.ObjectNode;
import com.nomagic.magicdraw.core.Application;


/**
 * @author kata_du
 * @version 1.0.0
 * @date 2025-12-18
 * @summary The `For_AC_Functions_ToLLMNoRAG_API_Key` class is responsible for executing interactions with a language model by processing prompts and managing API keys, along with facilitating chat functionalities using specified tokens and message configurations.
 */
public class For_AC_Functions_ToLLMNoRAG_API_Key 
{

/**
 * @param Prompt The `Prompt` parameter in the `execute` method is a string that represents the user's input message to be sent to the model for processing.
 * @param Ollama_API_Key The `Ollama_API_Key` parameter represents the API key used to authenticate and authorize access to the Ollama API for processing and analyzing the provided input messages.
 * @param sys_Msg The parameter `sys_Msg` of type `String` in the method `execute` represents a system-level message that sets the context for the interaction with the model, used to initialize the conversation or provide instructions.
 * @param modelName2 The `modelName2` parameter in the `execute` method is a string representing the name of the second language model to be used for processing the input prompt.
 * @return The `execute` method returns a `String` representing the response obtained from the model after processing the provided prompt and system message. This string contains the output generated by the chatWithModel function, which interacts with an external API to get a response based on the given input messages. If any exception occurs during this process, it returns `null`.
 * @summary This method sends a chat message to an AI model using the provided prompt and system message, returning the model's response.
 */
	// ADDED: String provider to determine which URL to hit
    public static String execute(String Prompt, String Ollama_API_Key, String sys_Msg, String modelName2, String provider) {
        
        String ollamaDLRAPIKey = Ollama_API_Key;
        String sysPrompt = sys_Msg;

        ObjectMapper objectMapper = new ObjectMapper();
        ArrayNode messages = objectMapper.createArrayNode();
        
        if (sysPrompt != null && !sysPrompt.isEmpty()) {
            ObjectNode systemMessage = objectMapper.createObjectNode();
            systemMessage.put("role", "system");
            systemMessage.put("content", sysPrompt);
            messages.add(systemMessage);
        }
        
        ObjectNode userMessage = objectMapper.createObjectNode();
        userMessage.put("role", "user");
        userMessage.put("content", Prompt);
        messages.add(userMessage);
        
        try {
            // Pass the provider down to chatWithModel
            return chatWithModel(ollamaDLRAPIKey, messages, objectMapper, modelName2, provider);
        } catch (IOException | InterruptedException e) {
            System.err.println("Error during API call: " + e.getMessage());
            e.printStackTrace();
            return null;
        }
    }

/**
 * @param token The `token` parameter in the `chatWithModel` method is a String that represents an authorization token used to authenticate API requests.
 * @param messages The `messages` parameter is an `ArrayNode` containing the sequence of input messages to be sent to the language model for generating a response.
 * @param objectMapper The `objectMapper` parameter is an instance of `ObjectMapper` used to serialize the request body and deserialize the response from the chat model API.
 * @param modelName2 `modelName2`: The identifier of the language model to be used for generating responses.
 * @return The `chatWithModel` method returns a `String` that represents the content of the message received from the model. This string is extracted from the JSON response body, specifically from the "content" field within the "choices" array. If the content is not found or is not textual, the method returns null.
 * @summary The `chatWithModel` method sends a chat request to a specified model via an HTTP API, processes the response, and extracts the content if it exists.
 */
	// Inside For_AC_Functions_ToLLMNoRAG_API_Key.java
	private static String chatWithModel(String token, ArrayNode messages, ObjectMapper objectMapper, String modelName2, String provider) throws IOException, InterruptedException {

        HttpClient client = HttpClient.newHttpClient();
        String url;

        // DYNAMIC URL ROUTING
        if ("Helmholtz Blablador".equals(provider)) {
            url = "https://api.helmholtz-blablador.fz-juelich.de/v1/chat/completions";
        } else {
            url = "https://ollama.nimbus.dlr.de/api/chat/completions";
        }

        ObjectNode requestBody = objectMapper.createObjectNode();
        requestBody.put("model", modelName2);
        requestBody.set("messages", messages);
        requestBody.put("temperature", 0.2); // Aligning with BlabladorAPIJava config

        HttpRequest request = HttpRequest.newBuilder()
                .uri(URI.create(url))
                .header("Authorization", "Bearer " + token.trim()) // TRIMMING TOKEN to prevent 401 error
                .header("Content-Type", "application/json; charset=utf-8") // ALIGNED with strict HTTP rules
                .POST(HttpRequest.BodyPublishers.ofString(requestBody.toString()))
                .build();

        HttpResponse<String> response = client.send(request, HttpResponse.BodyHandlers.ofString());
        String responseBody = response.body();

        JsonNode responseJson = objectMapper.readTree(responseBody);
        JsonNode contentNode = responseJson
                                .path("choices")
                                .path(0)
                                .path("message")
                                .path("content");

        if (contentNode.isTextual()) {
            return contentNode.asText();
        } else {
            Application.getInstance().getGUILog().showMessage("API Error Response: " + responseJson.toPrettyString()); 
            Application.getInstance().getGUILog().showMessage("\nCould not find 'content' value using safe access.");
            return null;
        }
    }
}
	


